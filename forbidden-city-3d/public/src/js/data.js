/** 形制图谱图例：统计各形制在中轴线上的出现次数 */
export function roofTypeLegend(planIds) {
  const counts = new Map();
  for (const id of planIds) {
    const s = STOP_BY_ID[id];
    if (!s || s.kind === 'overview') continue;
    counts.set(s.roofKey, (counts.get(s.roofKey) || 0) + 1);
  }
  return counts;
}
